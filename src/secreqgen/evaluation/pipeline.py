"""Evaluation pipeline for end-to-end RAG vs baseline comparison.

Orchestrates the full evaluation workflow:
1. Load test stories and ground truth
2. Run baseline (zero-shot) and RAG-enhanced generation
3. Match results against ground truth
4. Calculate metrics for both conditions
5. Compare and generate reports

This module is the main entry point for thesis evaluation.
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import TYPE_CHECKING, Any, Callable, Optional

from secreqgen.evaluation.baseline import BaselineRunner, ComparativeResults
from secreqgen.evaluation.metrics import ComparisonResult, MetricsBreakdown, MetricsCalculator
from secreqgen.evaluation.semantic_matcher import (
    GroundTruthRequirement,
    MatchResult,
    SemanticMatcher,
    load_ground_truth,
)
from secreqgen.generation.schemas import GenerationResult, UserStory

if TYPE_CHECKING:
    from secreqgen.generation.llm_client import OllamaClient
    from secreqgen.retrieval.retriever import SimpleRetriever

logger = logging.getLogger(__name__)


@dataclass
class StoryEvaluationResult:
    """Evaluation results for a single user story.

    Contains matched results and metrics for both baseline and RAG
    generation for one user story, enabling per-story analysis.

    Attributes:
        story_id: The user story ID being evaluated.
        story_title: Title of the user story.
        ground_truth: Ground truth requirements for this story.
        baseline_result: Generation result from zero-shot mode (None if failed).
        rag_result: Generation result from RAG mode (None if failed).
        baseline_matches: Match results for baseline generation.
        rag_matches: Match results for RAG generation.
        baseline_metrics: Metrics for baseline generation.
        rag_metrics: Metrics for RAG generation.
    """

    story_id: str
    story_title: str
    ground_truth: list[GroundTruthRequirement]
    baseline_result: Optional[GenerationResult]
    rag_result: Optional[GenerationResult]
    baseline_matches: list[MatchResult]
    rag_matches: list[MatchResult]
    baseline_metrics: MetricsBreakdown
    rag_metrics: MetricsBreakdown

    @property
    def baseline_requirement_count(self) -> int:
        """Number of requirements generated by baseline."""
        return len(self.baseline_result.requirements) if self.baseline_result else 0

    @property
    def rag_requirement_count(self) -> int:
        """Number of requirements generated by RAG."""
        return len(self.rag_result.requirements) if self.rag_result else 0

    @property
    def ground_truth_count(self) -> int:
        """Number of ground truth requirements."""
        return len(self.ground_truth)


@dataclass
class EvaluationPipelineResult:
    """Complete results from an evaluation pipeline run.

    Contains all per-story results plus aggregate metrics and comparison
    data for the full evaluation.

    Attributes:
        per_story_results: Evaluation results for each user story.
        aggregate_baseline_metrics: Combined metrics across all baseline results.
        aggregate_rag_metrics: Combined metrics across all RAG results.
        comparison: Comparison of RAG vs baseline aggregate metrics.
        comparative_results: Raw generation results from BaselineRunner.
        run_timestamp: When the evaluation was executed.
        config: Configuration used for the evaluation.
    """

    per_story_results: list[StoryEvaluationResult]
    aggregate_baseline_metrics: MetricsBreakdown
    aggregate_rag_metrics: MetricsBreakdown
    comparison: ComparisonResult
    comparative_results: ComparativeResults
    run_timestamp: datetime = field(default_factory=datetime.now)
    config: dict[str, Any] = field(default_factory=dict)

    @property
    def total_stories(self) -> int:
        """Total number of stories evaluated."""
        return len(self.per_story_results)

    @property
    def meets_thesis_target(self) -> bool:
        """True if RAG meets the 20% F1 improvement threshold."""
        return self.comparison.meets_threshold

    def get_partial_matches(self) -> list[tuple[str, MatchResult]]:
        """Get all partial matches for manual review.

        Returns:
            List of (story_id, match_result) tuples for partial matches.
        """
        partials = []
        for story_result in self.per_story_results:
            for match in story_result.rag_matches:
                if match.is_partial:
                    partials.append((story_result.story_id, match))
        return partials

    def summary(self) -> str:
        """Generate a human-readable summary of the evaluation."""
        status = "✓ THESIS TARGET MET" if self.meets_thesis_target else "✗ THESIS TARGET NOT MET"

        lines = [
            "=" * 60,
            "EVALUATION PIPELINE RESULTS",
            "=" * 60,
            f"Run Time: {self.run_timestamp.strftime('%Y-%m-%d %H:%M:%S')}",
            f"Stories Evaluated: {self.total_stories}",
            "",
            "AGGREGATE METRICS:",
            "-" * 40,
            f"                    Baseline    RAG         Delta",
            f"  Precision:        {self.aggregate_baseline_metrics.precision:>6.2%}      {self.aggregate_rag_metrics.precision:>6.2%}      {self.comparison.precision_delta:>+7.2%}",
            f"  Recall:           {self.aggregate_baseline_metrics.recall:>6.2%}      {self.aggregate_rag_metrics.recall:>6.2%}      {self.comparison.recall_delta:>+7.2%}",
            f"  F1 Score:         {self.aggregate_baseline_metrics.f1_score:>6.2%}      {self.aggregate_rag_metrics.f1_score:>6.2%}      {self.comparison.f1_delta:>+7.2%}",
            f"  Hallucination:    {self.aggregate_baseline_metrics.hallucination_rate:>6.2%}      {self.aggregate_rag_metrics.hallucination_rate:>6.2%}      {self.comparison.hallucination_delta:>+7.2%}",
            "",
            f"  F1 Improvement: {self.comparison.f1_improvement_pct:+.1f}%",
            f"  {status} (target: {(self.comparison.improvement_threshold - 1) * 100:.0f}%)",
            "",
            "GENERATION COUNTS:",
            "-" * 40,
            f"  Baseline Requirements: {self.aggregate_baseline_metrics.total_generated}",
            f"  RAG Requirements:      {self.aggregate_rag_metrics.total_generated}",
            f"  Ground Truth Total:    {self.aggregate_baseline_metrics.total_ground_truth}",
            "",
            f"  Partial Matches (need review): {len(self.get_partial_matches())}",
            "=" * 60,
        ]

        return "\n".join(lines)


# Type alias for progress callback
ProgressCallback = Callable[[str, int, int], None]


class EvaluationPipeline:
    """End-to-end evaluation pipeline for RAG vs baseline comparison.

    Orchestrates the complete evaluation workflow for the thesis:
    loading data, running both generation modes, matching against
    ground truth, and calculating comparative metrics.

    The pipeline is designed to be:
    - Fault-tolerant: Continues on per-story failures
    - Observable: Progress callbacks for CLI integration
    - Configurable: Adjustable thresholds and settings

    Example:
        >>> pipeline = EvaluationPipeline(llm_client, retriever)
        >>> result = pipeline.run(
        ...     stories_path="data/user_stories/test.json",
        ...     ground_truth_path="data/ground_truth/test.json"
        ... )
        >>> print(result.summary())
        >>> if result.meets_thesis_target:
        ...     print("RAG shows significant improvement!")
    """

    def __init__(
        self,
        llm_client: OllamaClient,
        retriever: Optional[SimpleRetriever] = None,
        match_threshold: float = 0.85,
        partial_threshold: float = 0.70,
        improvement_threshold: float = 1.20,
        system_context: Optional[str] = None,
    ) -> None:
        """Initialize the evaluation pipeline.

        Args:
            llm_client: Ollama client for LLM generation.
            retriever: Retriever for RAG mode. If None, only baseline available.
            match_threshold: Similarity threshold for a "match" (default 0.85).
            partial_threshold: Similarity threshold for "partial" (default 0.70).
            improvement_threshold: Required F1 improvement factor (default 1.20 = 20%).
            system_context: Optional system context to inject into prompts.
        """
        self.llm_client = llm_client
        self.retriever = retriever
        self.match_threshold = match_threshold
        self.partial_threshold = partial_threshold
        self.improvement_threshold = improvement_threshold
        self.system_context = system_context

        # Initialize components
        self._runner = BaselineRunner(
            llm_client=llm_client,
            retriever=retriever,
            system_context=system_context,
        )
        self._matcher = SemanticMatcher(
            match_threshold=match_threshold,
            partial_threshold=partial_threshold,
        )
        self._calculator = MetricsCalculator()

    def run(
        self,
        stories_path: str | Path,
        ground_truth_path: str | Path,
        progress_callback: Optional[ProgressCallback] = None,
    ) -> EvaluationPipelineResult:
        """Run the complete evaluation pipeline.

        Args:
            stories_path: Path to JSON file containing user stories.
            ground_truth_path: Path to JSON file containing ground truth.
            progress_callback: Optional callback(phase, current, total) for progress.

        Returns:
            EvaluationPipelineResult with all metrics and comparisons.

        Raises:
            FileNotFoundError: If stories or ground truth files don't exist.
            ValueError: If file format is invalid.
        """
        logger.info("Starting evaluation pipeline")

        # Phase 1: Load data
        if progress_callback:
            progress_callback("loading", 0, 2)

        stories = self._load_stories(stories_path)
        logger.info(f"Loaded {len(stories)} user stories from {stories_path}")

        if progress_callback:
            progress_callback("loading", 1, 2)

        ground_truth_map = self._load_ground_truth(ground_truth_path)
        total_gt = sum(len(gt) for gt in ground_truth_map.values())
        logger.info(f"Loaded {total_gt} ground truth requirements for {len(ground_truth_map)} stories")

        if progress_callback:
            progress_callback("loading", 2, 2)

        # Phase 2: Run generation
        logger.info("Running comparative generation (baseline + RAG)...")
        comparative_results = self._runner.run_comparative(
            stories=stories,
            progress_callback=progress_callback,
        )

        # Phase 3: Match and evaluate each story
        logger.info("Matching results against ground truth...")
        per_story_results = self._evaluate_per_story(
            stories=stories,
            ground_truth_map=ground_truth_map,
            baseline_results=comparative_results.baseline_results,
            rag_results=comparative_results.rag_results,
            progress_callback=progress_callback,
        )

        # Phase 4: Calculate aggregate metrics
        logger.info("Calculating aggregate metrics...")
        all_baseline_matches: list[MatchResult] = []
        all_rag_matches: list[MatchResult] = []

        for story_result in per_story_results:
            all_baseline_matches.extend(story_result.baseline_matches)
            all_rag_matches.extend(story_result.rag_matches)

        aggregate_baseline = self._calculator.calculate(
            matches=all_baseline_matches,
            total_ground_truth=total_gt,
        )
        aggregate_rag = self._calculator.calculate(
            matches=all_rag_matches,
            total_ground_truth=total_gt,
        )

        # Phase 5: Compare conditions
        comparison = self._calculator.compare_conditions(
            baseline=aggregate_baseline,
            rag=aggregate_rag,
            improvement_threshold=self.improvement_threshold,
        )

        result = EvaluationPipelineResult(
            per_story_results=per_story_results,
            aggregate_baseline_metrics=aggregate_baseline,
            aggregate_rag_metrics=aggregate_rag,
            comparison=comparison,
            comparative_results=comparative_results,
            config={
                "match_threshold": self.match_threshold,
                "partial_threshold": self.partial_threshold,
                "improvement_threshold": self.improvement_threshold,
                "stories_path": str(stories_path),
                "ground_truth_path": str(ground_truth_path),
            },
        )

        logger.info(f"Evaluation complete. Thesis target met: {result.meets_thesis_target}")

        return result

    def run_from_data(
        self,
        stories: list[UserStory],
        ground_truth_map: dict[str, list[GroundTruthRequirement]],
        progress_callback: Optional[ProgressCallback] = None,
    ) -> EvaluationPipelineResult:
        """Run the pipeline with pre-loaded data.

        This method is useful for testing or when data is already
        loaded from another source.

        Args:
            stories: List of UserStory objects to evaluate.
            ground_truth_map: Dict mapping story_id -> list of ground truth requirements.
            progress_callback: Optional progress callback.

        Returns:
            EvaluationPipelineResult with all metrics and comparisons.
        """
        logger.info(f"Running evaluation on {len(stories)} pre-loaded stories")

        # Run generation
        comparative_results = self._runner.run_comparative(
            stories=stories,
            progress_callback=progress_callback,
        )

        # Match and evaluate
        per_story_results = self._evaluate_per_story(
            stories=stories,
            ground_truth_map=ground_truth_map,
            baseline_results=comparative_results.baseline_results,
            rag_results=comparative_results.rag_results,
            progress_callback=progress_callback,
        )

        # Calculate aggregates
        total_gt = sum(len(gt) for gt in ground_truth_map.values())
        all_baseline_matches = []
        all_rag_matches = []

        for story_result in per_story_results:
            all_baseline_matches.extend(story_result.baseline_matches)
            all_rag_matches.extend(story_result.rag_matches)

        aggregate_baseline = self._calculator.calculate(all_baseline_matches, total_gt)
        aggregate_rag = self._calculator.calculate(all_rag_matches, total_gt)

        comparison = self._calculator.compare_conditions(
            baseline=aggregate_baseline,
            rag=aggregate_rag,
            improvement_threshold=self.improvement_threshold,
        )

        return EvaluationPipelineResult(
            per_story_results=per_story_results,
            aggregate_baseline_metrics=aggregate_baseline,
            aggregate_rag_metrics=aggregate_rag,
            comparison=comparison,
            comparative_results=comparative_results,
            config={
                "match_threshold": self.match_threshold,
                "partial_threshold": self.partial_threshold,
                "improvement_threshold": self.improvement_threshold,
            },
        )

    def _load_stories(self, path: str | Path) -> list[UserStory]:
        """Load user stories from a JSON file.

        Expected format:
        {
            "user_stories": [
                {"id": "US-001", "title": "...", "story": "...", "acceptance_criteria": [...]}
            ]
        }
        """
        path = Path(path)
        if not path.exists():
            raise FileNotFoundError(f"Stories file not found: {path}")

        with open(path, encoding="utf-8") as f:
            data = json.load(f)

        if "user_stories" not in data:
            raise ValueError(f"Invalid stories file format: missing 'user_stories' key in {path}")

        stories = []
        for item in data["user_stories"]:
            story = UserStory(
                id=item["id"],
                title=item["title"],
                story=item["story"],
                acceptance_criteria=item.get("acceptance_criteria", []),
            )
            stories.append(story)

        return stories

    def _load_ground_truth(
        self, path: str | Path
    ) -> dict[str, list[GroundTruthRequirement]]:
        """Load ground truth from a JSON file.

        Expected format (per thesis spec):
        {
            "ground_truth": [
                {
                    "story_id": "US-001",
                    "requirements": [
                        {"id": "GT-001", "title": "...", "description": "...", "asvs_category": "..."}
                    ]
                }
            ]
        }

        Returns:
            Dict mapping story_id -> list of GroundTruthRequirement.
        """
        path = Path(path)
        if not path.exists():
            raise FileNotFoundError(f"Ground truth file not found: {path}")

        with open(path, encoding="utf-8") as f:
            data = json.load(f)

        if "ground_truth" not in data:
            raise ValueError(f"Invalid ground truth format: missing 'ground_truth' key in {path}")

        gt_map: dict[str, list[GroundTruthRequirement]] = {}

        for story_gt in data["ground_truth"]:
            story_id = story_gt["story_id"]
            requirements = load_ground_truth(story_gt.get("requirements", []))
            gt_map[story_id] = requirements

        return gt_map

    def _evaluate_per_story(
        self,
        stories: list[UserStory],
        ground_truth_map: dict[str, list[GroundTruthRequirement]],
        baseline_results: list[GenerationResult],
        rag_results: list[GenerationResult],
        progress_callback: Optional[ProgressCallback] = None,
    ) -> list[StoryEvaluationResult]:
        """Evaluate each story against its ground truth.

        Args:
            stories: Original user stories.
            ground_truth_map: Story ID -> ground truth mapping.
            baseline_results: Results from baseline generation.
            rag_results: Results from RAG generation.
            progress_callback: Optional progress callback.

        Returns:
            List of per-story evaluation results.
        """
        # Build lookup maps by story ID
        baseline_map = {r.user_story.id: r for r in baseline_results}
        rag_map = {r.user_story.id: r for r in rag_results}

        results = []
        total = len(stories)

        for i, story in enumerate(stories):
            if progress_callback:
                progress_callback("matching", i, total)

            story_id = story.id
            gt = ground_truth_map.get(story_id, [])
            total_gt = len(gt)

            # Get generation results (may be None if generation failed)
            baseline_result = baseline_map.get(story_id)
            rag_result = rag_map.get(story_id)

            # Match baseline results
            if baseline_result and baseline_result.requirements:
                baseline_matches = self._matcher.match_requirements(
                    generated=baseline_result.requirements,
                    ground_truth=gt,
                )
            else:
                baseline_matches = []

            # Match RAG results
            if rag_result and rag_result.requirements:
                # Clear cache between stories to avoid cross-contamination
                self._matcher.clear_cache()
                rag_matches = self._matcher.match_requirements(
                    generated=rag_result.requirements,
                    ground_truth=gt,
                )
            else:
                rag_matches = []

            # Calculate metrics for this story
            baseline_metrics = self._calculator.calculate(baseline_matches, total_gt)
            rag_metrics = self._calculator.calculate(rag_matches, total_gt)

            results.append(
                StoryEvaluationResult(
                    story_id=story_id,
                    story_title=story.title,
                    ground_truth=gt,
                    baseline_result=baseline_result,
                    rag_result=rag_result,
                    baseline_matches=baseline_matches,
                    rag_matches=rag_matches,
                    baseline_metrics=baseline_metrics,
                    rag_metrics=rag_metrics,
                )
            )

        if progress_callback:
            progress_callback("matching", total, total)

        return results


def create_evaluation_pipeline(
    llm_client: OllamaClient,
    vectorstore_path: Optional[str] = None,
    embedding_model: str = "all-mpnet-base-v2",
    match_threshold: float = 0.85,
    partial_threshold: float = 0.70,
    improvement_threshold: float = 1.20,
    system_context: Optional[str] = None,
) -> EvaluationPipeline:
    """Factory function to create an EvaluationPipeline with standard configuration.

    Args:
        llm_client: Ollama client for LLM generation.
        vectorstore_path: Path to ChromaDB vector store. If None, only baseline available.
        embedding_model: Embedding model for retriever (default: all-mpnet-base-v2).
        match_threshold: Similarity threshold for matches (default 0.85).
        partial_threshold: Similarity threshold for partials (default 0.70).
        improvement_threshold: F1 improvement factor target (default 1.20 = 20%).
        system_context: Optional system context to inject.

    Returns:
        Configured EvaluationPipeline instance.
    """
    retriever = None

    if vectorstore_path is not None:
        # Lazy imports
        from secreqgen.ingestion.embedder import DocumentEmbedder
        from secreqgen.retrieval.retriever import SimpleRetriever
        from secreqgen.retrieval.vectorstore import SecReqGenVectorStore

        embedder = DocumentEmbedder(model_name=embedding_model)
        vectorstore = SecReqGenVectorStore(persist_directory=vectorstore_path)
        retriever = SimpleRetriever(vectorstore=vectorstore, embedder=embedder)

    return EvaluationPipeline(
        llm_client=llm_client,
        retriever=retriever,
        match_threshold=match_threshold,
        partial_threshold=partial_threshold,
        improvement_threshold=improvement_threshold,
        system_context=system_context,
    )
